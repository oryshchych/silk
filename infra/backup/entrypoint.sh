#!/bin/sh
# stanza-create ідемпотентний: на першому запуску створює репозиторій,
# далі нічого не робить. Помилка тут мусить бути видимою в логах, а не
# тихо пропущеною — інакше «бекапи налаштовані», а репозиторію немає.
set -eu

pgbackrest --stanza="${PGBACKREST_STANZA:-store}" stanza-create || \
  echo "stanza-create не пройшов (можливо, вже існує) — перевірте логи" >&2

exec "$@"
